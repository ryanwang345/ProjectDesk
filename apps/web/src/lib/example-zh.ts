function cleanMeaning(meaning: string) {
  const first = meaning.split(/[；;，,、/]/)[0]?.trim() ?? meaning.trim()
  return first.replace(/^(to\s+)/i, '')
}

export function translateExample(sentence: string, word: string, meaning: string): string {
  const trimmed = sentence.trim()
  if (!trimmed) return ''
  const exact = EXACT_ZH[trimmed]
  if (exact) return exact

  const target = word.trim()
  if (!target) return ''
  const index = trimmed.toLowerCase().indexOf(target.toLowerCase())
  if (index < 0) return ''

  const frame = `${trimmed.slice(0, index)}%s${trimmed.slice(index + target.length)}`
  const template = FRAME_ZH[frame]
  const zhWord = cleanMeaning(meaning) || target
  if (template) {
    return template.replace('%s', zhWord)
  }
  return ''
}
