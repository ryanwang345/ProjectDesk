func worldVocabulary() ([]worldVocabularyEntry, error) {
	seen := map[string]bool{}
	for _, entry := range worldVocabularyList {
		key := strings.ToLower(entry.Word)
		if seen[key] || entry.Word != strings.TrimSpace(entry.Word) || entry.Definition == "" {
			return nil, fmt.Errorf("invalid or duplicate world vocabulary: %s", entry.Word)
		}
		if entry.Kind != "n" && entry.Kind != "adj" {
			return nil, fmt.Errorf("unsupported world vocabulary part of speech: %s", entry.Kind)
		}
		if err := ValidateEnglish(EnglishInput{Word: entry.Word, Meaning: entry.Meaning, Examples: entry.Examples}); err != nil {
			return nil, fmt.Errorf("world vocabulary %s: %w", entry.Word, err)
		}
		seen[key] = true
	}
	return worldVocabularyList, nil
}

// Use the ordinary English cards so search, pronunciation, lessons and review
// work without a separate library. Existing cards and review states are retained.
func seedWorldVocabulary(ctx context.Context, tx pgx.Tx, have map[string]bool) error {
	entries, err := worldVocabulary()
	if err != nil {
		return err
	}
	for _, entry := range entries {
		key := strings.ToLower(entry.Word)
		if have[key] {
			continue
		}
		senses, err := json.Marshal(WordSenses{{Pos: entry.Kind, En: entry.Definition, Zh: entry.Meaning}})
		if err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, `INSERT INTO english_cards (word,meaning,examples,senses,generated) VALUES ($1,$2,$3,$4::jsonb,true)`, entry.Word, entry.Meaning, entry.Examples, senses); err != nil {
			return err
		}
		have[key] = true
	}
	return nil
}
